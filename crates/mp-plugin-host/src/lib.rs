//! The WebAssembly plugin host: Mission Planner's plugins, loaded from `plugins/` beside the
//! executable and run on wasmtime's component model.
//!
//! PLAN.md §13.6 row 96, on row 95's experiment (removed 2026-10-05, this crate its successor). The C# loads
//! every `.dll` in its plugins folder and compiles every `.cs` there at run time
//! (`Plugin/PluginLoader.cs`); each plugin derives `MissionPlanner.Plugin.Plugin` and reaches the
//! application through a `PluginHost` (`Plugin/Plugin.cs`). Neither a .NET assembly nor run-time
//! C# can exist here; a plugin is a WebAssembly component of the world in `wit/plugin.wit`:
//!
//! * the `Plugin` lifecycle is the world's exports - `name`, `version`, `author`,
//!   `loop-rate-hz`, `init`, `loaded`, `loop`, `exit` - with a menu entry's click and a form's
//!   event, which the C# delivers as .NET events;
//! * `PluginHost` is the `host` interface the plugin imports, and [`Surface`] is the Rust side of
//!   it: the application implements it (through [`ChannelSurface`], which carries every call to
//!   the window's thread as a [`Request`]), a test implements it with a script.
//!
//! [`Plugin`] is one plugin loaded and driven synchronously; [`PluginHost`] is
//! `PluginLoader.LoadAll` and `MainV2.PluginThread`: every `*.wasm` in a folder, each on a thread
//! of its own at its `loopratehz`, with fuel.
//!
//! What the C# cannot do and this does: a plugin that panics or traps is a status line and is
//! unloaded, where the C#'s exception takes down its thread or the application; a plugin that
//! never returns is stopped by its fuel, where the C#'s plugin thread hangs; a plugin reaches only
//! what the world imports - no file, socket or clock the host did not hand it.

