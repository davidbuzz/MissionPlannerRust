    /// Every node of `tree`, depth first as `PolyTreeToPaths` visits them, with its depth.
    fn dump(tree: &PolyTree) -> Vec<(usize, Vec<IntPoint>)> {
        fn walk(
            tree: &PolyTree,
            index: usize,
            depth: usize,
            out: &mut Vec<(usize, Vec<IntPoint>)>,
        ) {
            out.push((depth, tree.nodes[index].polygon.clone()));
            for &child in &tree.nodes[index].childs {
                walk(tree, child, depth + 1, out);
            }
        }
        let mut out = Vec::new();
        for &child in &tree.childs {
            walk(tree, child, 1, &mut out);
        }
        out
    }

