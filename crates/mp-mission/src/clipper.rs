    /// `ClipperBase.InsertLocalMinima`, `clipper.cs:1091-1110`.
    fn insert_local_minima(&mut self, new_lm: MinimaId) {
        match self.minima_list {
            None => self.minima_list = Some(new_lm),
            Some(head) if self.minima[new_lm].y >= self.minima[head].y => {
                self.minima[new_lm].next = Some(head);
                self.minima_list = Some(new_lm);
            }
            Some(head) => {
                let mut tmp_lm = head;
                while let Some(next) = self.minima[tmp_lm].next {
                    if self.minima[new_lm].y < self.minima[next].y {
                        tmp_lm = next;
                    } else {
                        break;
                    }
                }
                self.minima[new_lm].next = self.minima[tmp_lm].next;
                self.minima[tmp_lm].next = Some(new_lm);
            }
        }
    }

