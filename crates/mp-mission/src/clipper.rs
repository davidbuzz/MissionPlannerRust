    /// `Clipper.IntersectEdges`, `clipper.cs:2481-2680`, for two closed subject edges in a union.
    /// The `use_lines` block (`:2493-2537`) is for open paths.
    fn intersect_edges(&mut self, e1: EdgeId, e2: EdgeId, pt: IntPoint) -> Result<()> {
        //e1 will be to the left of e2 BELOW the intersection. Therefore e1 is before
        //e2 in AEL except when e1 is being inserted at the intersection point ...

        let e1_contributing = self.edges[e1].out_idx >= 0;
        let e2_contributing = self.edges[e2].out_idx >= 0;

        //update winding counts...
        //assumes that e1 will be to the Right of e2 ABOVE the intersection
        // Same polytype, and not EvenOdd filling:
        let (e1_wind_delta, e2_wind_delta) = (self.edges[e1].wind_delta, self.edges[e2].wind_delta);
        if self.edges[e1].wind_cnt + e2_wind_delta == 0 {
            self.edges[e1].wind_cnt = -self.edges[e1].wind_cnt;
        } else {
            self.edges[e1].wind_cnt += e2_wind_delta;
        }
        if self.edges[e2].wind_cnt - e1_wind_delta == 0 {
            self.edges[e2].wind_cnt = -self.edges[e2].wind_cnt;
        } else {
            self.edges[e2].wind_cnt -= e1_wind_delta;
        }

        // Both are subject edges: each one's fill type is the subject's, and its fill type 2 the
        // clip's; here those are the same.
        let fill_type = self.fill_type;
        let wc = move |wind_cnt: i32| match fill_type {
            FillType::Positive => wind_cnt,
            FillType::Negative => -wind_cnt,
        };
        let e1_wc = wc(self.edges[e1].wind_cnt);
        let e2_wc = wc(self.edges[e2].wind_cnt);

        if e1_contributing && e2_contributing {
            // (e1.PolyTyp != e2.PolyTyp && ...) is false
            if (e1_wc != 0 && e1_wc != 1) || (e2_wc != 0 && e2_wc != 1) {
                self.add_local_max_poly(e1, e2, pt)?;
            } else {
                self.add_out_pt(e1, pt)?;
                self.add_out_pt(e2, pt)?;
                self.swap_sides(e1, e2);
                self.swap_poly_indexes(e1, e2);
            }
        } else if e1_contributing {
            if e2_wc == 0 || e2_wc == 1 {
                self.add_out_pt(e1, pt)?;
                self.swap_sides(e1, e2);
                self.swap_poly_indexes(e1, e2);
            }
        } else if e2_contributing {
            if e1_wc == 0 || e1_wc == 1 {
                self.add_out_pt(e2, pt)?;
                self.swap_sides(e1, e2);
                self.swap_poly_indexes(e1, e2);
            }
        } else if (e1_wc == 0 || e1_wc == 1) && (e2_wc == 0 || e2_wc == 1) {
            //neither edge is currently contributing ...
            let e1_wc2 = i64::from(wc(self.edges[e1].wind_cnt2));
            let e2_wc2 = i64::from(wc(self.edges[e2].wind_cnt2));

            // Same polytype: no AddLocalMinPoly for differing ones (clipper.cs:2653-2656).
            if e1_wc == 1 && e2_wc == 1 {
                // ClipType.ctUnion
                if e1_wc2 <= 0 && e2_wc2 <= 0 {
                    self.add_local_min_poly(e1, e2, pt)?;
                }
            } else {
                self.swap_sides(e1, e2);
            }
        }
        Ok(())
    }

    /// `Clipper.ProcessHorizontals`, `clipper.cs:2699-2704`.
    fn process_horizontals(&mut self) -> Result<()> {
        while let Some(horz_edge) = self.pop_edge_from_sel() {
            self.process_horizontal(horz_edge)?;
        }
        Ok(())
    }

    /// `Clipper.GetHorzDirection`, `clipper.cs:2707-2721`: direction, left, right.
    fn get_horz_direction(&self, horz_edge: EdgeId) -> (Direction, i64, i64) {
        let e = &self.edges[horz_edge];
        if e.bot.x < e.top.x {
            (Direction::LeftToRight, e.bot.x, e.top.x)
        } else {
            (Direction::RightToLeft, e.top.x, e.bot.x)
        }
    }

    /// The `eNextHorz` loops of `clipper.cs:2806-2818` and `:2858-2871`: a join from every
    /// contributing horizontal in the SEL that overlaps `horz_edge` to `op1`, then a ghost join.
    fn join_overlapping_horizontals(
        &mut self,
        horz_edge: EdgeId,
        op1: OutPtId,
        ghost_off: IntPoint,
    ) -> Result<()> {
        let mut e_next_horz = self.sorted_edges;
        while let Some(next_horz) = e_next_horz {
            if self.edges[next_horz].out_idx >= 0
                && horz_segments_overlap(
                    self.edges[horz_edge].bot.x,
                    self.edges[horz_edge].top.x,
                    self.edges[next_horz].bot.x,
                    self.edges[next_horz].top.x,
                )
            {
                let op2 = self.get_last_out_pt(next_horz)?;
                self.add_join(op2, op1, self.edges[next_horz].top);
            }
            e_next_horz = self.edges[next_horz].next_in_sel;
        }
        self.add_ghost_join(op1, ghost_off);
        Ok(())
    }

    /// `Clipper.ProcessHorizontal`, `clipper.cs:2724-2910`. `m_Maxima` is only ever built when
    /// `StrictlySimple` (`:3193`), so `currMax` is always null and its blocks are left out.
    #[allow(clippy::too_many_lines)] // one C# method, kept in one piece so it reads against clipper.cs
    fn process_horizontal(&mut self, mut horz_edge: EdgeId) -> Result<()> {
        let is_open = self.edges[horz_edge].wind_delta == 0;

        let (mut dir, mut horz_left, mut horz_right) = self.get_horz_direction(horz_edge);

        let mut e_last_horz = horz_edge;
        let mut e_max_pair = None;
        while let Some(next_in_lml) = self.edges[e_last_horz].next_in_lml {
            if !is_horizontal(&self.edges[next_in_lml]) {
                break;
            }
            e_last_horz = next_in_lml;
        }
        if self.edges[e_last_horz].next_in_lml.is_none() {
            e_max_pair = self.get_maxima_pair(e_last_horz);
        }

        let mut op1: Option<OutPtId> = None;
        loop {
            //loop through consec. horizontal edges
            let is_last_horz = horz_edge == e_last_horz;
            let mut e = self.get_next_in_ael(horz_edge, dir);
            while let Some(current) = e {
                if (dir == Direction::LeftToRight && self.edges[current].curr.x > horz_right)
                    || (dir == Direction::RightToLeft && self.edges[current].curr.x < horz_left)
                {
                    break;
                }

                //Also break if we've got to the end of an intermediate horizontal edge ...
                //nb: Smaller Dx's are to the right of larger Dx's ABOVE the horizontal.
                if self.edges[current].curr.x == self.edges[horz_edge].top.x
                    && let Some(next_in_lml) = self.edges[horz_edge].next_in_lml
                    && self.edges[current].dx < self.edges[next_in_lml].dx
                {
                    break;
                }

                if self.edges[horz_edge].out_idx >= 0 && !is_open {
                    //note: may be done multiple times
                    let op = self.add_out_pt(horz_edge, self.edges[current].curr)?;
                    op1 = Some(op);
                    self.join_overlapping_horizontals(horz_edge, op, self.edges[horz_edge].bot)?;
                }

                //OK, so far we're still in range of the horizontal Edge  but make sure
                //we're at the last of consec. horizontals when matching with eMaxPair
                if Some(current) == e_max_pair && is_last_horz {
                    if self.edges[horz_edge].out_idx >= 0 {
                        self.add_local_max_poly(horz_edge, current, self.edges[horz_edge].top)?;
                    }
                    self.delete_from_ael(horz_edge);
                    self.delete_from_ael(current);
                    return Ok(());
                }

                let pt = IntPoint::new(self.edges[current].curr.x, self.edges[horz_edge].curr.y);
                if dir == Direction::LeftToRight {
                    self.intersect_edges(horz_edge, current, pt)?;
                } else {
                    self.intersect_edges(current, horz_edge, pt)?;
                }
                let e_next = self.get_next_in_ael(current, dir);
                self.swap_positions_in_ael(horz_edge, current);
                e = e_next;
            } //end while(e != null)

            //Break out of loop if HorzEdge.NextInLML is not also horizontal ...
            match self.edges[horz_edge].next_in_lml {
                Some(next_in_lml) if is_horizontal(&self.edges[next_in_lml]) => {}
                _ => break,
            }

            horz_edge = self.update_edge_into_ael(horz_edge)?;
            if self.edges[horz_edge].out_idx >= 0 {
                self.add_out_pt(horz_edge, self.edges[horz_edge].bot)?;
            }
            (dir, horz_left, horz_right) = self.get_horz_direction(horz_edge);
        } //end for (;;)

        if self.edges[horz_edge].out_idx >= 0 && op1.is_none() {
            let op = self.get_last_out_pt(horz_edge)?;
            self.join_overlapping_horizontals(horz_edge, op, self.edges[horz_edge].top)?;
        }

        if self.edges[horz_edge].next_in_lml.is_some() {
            if self.edges[horz_edge].out_idx >= 0 {
                let op = self.add_out_pt(horz_edge, self.edges[horz_edge].top)?;

                horz_edge = self.update_edge_into_ael(horz_edge)?;
                if self.edges[horz_edge].wind_delta == 0 {
                    return Ok(());
                }
                //nb: HorzEdge is no longer horizontal here
                let horz = self.edges[horz_edge];
                if let Some(e_prev) = horz.prev_in_ael
                    && self.edges[e_prev].curr.x == horz.bot.x
                    && self.edges[e_prev].curr.y == horz.bot.y
                    && self.edges[e_prev].wind_delta != 0
                    && (self.edges[e_prev].out_idx >= 0
                        && self.edges[e_prev].curr.y > self.edges[e_prev].top.y
                        && slopes_equal_edges(&horz, &self.edges[e_prev]))
                {
                    let op2 = self.add_out_pt(e_prev, horz.bot)?;
                    self.add_join(op, op2, horz.top);
                } else if let Some(e_next) = horz.next_in_ael
                    && self.edges[e_next].curr.x == horz.bot.x
                    && self.edges[e_next].curr.y == horz.bot.y
                    && self.edges[e_next].wind_delta != 0
                    && self.edges[e_next].out_idx >= 0
                    && self.edges[e_next].curr.y > self.edges[e_next].top.y
                    && slopes_equal_edges(&horz, &self.edges[e_next])
                {
                    let op2 = self.add_out_pt(e_next, horz.bot)?;
                    self.add_join(op, op2, horz.top);
                }
            } else {
                self.update_edge_into_ael(horz_edge)?;
            }
        } else {
            if self.edges[horz_edge].out_idx >= 0 {
                self.add_out_pt(horz_edge, self.edges[horz_edge].top)?;
            }
            self.delete_from_ael(horz_edge);
        }
        Ok(())
    }

