//! square join types and open end types, and the flat `Paths` result. Each place the C# branches on
//! one of them says so where the branch would be.
//!
//! The union is integer arithmetic on `Int64` coordinates - the rotary pattern's are millimetres
//! (`Grid.cs:250`) - with doubles only for edge slopes (`SetDx`), top-of-beam crossings (`TopX`),
