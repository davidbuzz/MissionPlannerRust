//! ClipperLib's polygon offset as `Grid.CreateRotary` uses it, transliterated.
//!
//! Replaces the parts of `ExtLibs/Utilities/clipper.cs` - Angus Johnson's Clipper 6.4.2, the C#
//! translation Mission Planner vendors - that `ClipperOffset.Execute(ref PolyTree, double)`
//! (`clipper.cs:4792-4832`) reaches for what `Grid.cs:248-257` gives it: one closed path, mitred
//! joins, the default miter limit and arc tolerance, and a delta that is never positive. That is
//! the offset itself (`ClipperOffset`, `clipper.cs:4449-4922`) and the Vatti union that cleans it up
//! (`Clipper`, `ClipperBase`, `clipper.cs:547-4141`), run on subject paths only, closed, with the
//! negative fill rule, building a `PolyTree`.
//!
//! What the offset never reaches is not ported: open paths (`use_lines` - skip edges, zero wind
