// Each C# class instance becomes an entry in an arena, and each reference to one its index. Entries
// are only ever added, so an index, once made, stays valid.
macro_rules! arena {
    ($(#[$doc:meta])* $arena:ident, $id:ident, $item:ty) => {
        $(#[$doc])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
        struct $id(usize);

        #[derive(Debug, Default)]
        struct $arena(Vec<$item>);

        impl $arena {
            fn push(&mut self, item: $item) -> $id {
                self.0.push(item);
                $id(self.0.len() - 1)
            }

            #[allow(dead_code)] // not every arena is counted
            fn len(&self) -> usize {
                self.0.len()
            }
        }

        impl std::ops::Index<$id> for $arena {
            type Output = $item;

            #[allow(clippy::indexing_slicing)] // an id is only made by `push`, and nothing is removed
            fn index(&self, id: $id) -> &$item {
                &self.0[id.0]
            }
        }

        impl std::ops::IndexMut<$id> for $arena {
            #[allow(clippy::indexing_slicing)] // an id is only made by `push`, and nothing is removed
            fn index_mut(&mut self, id: $id) -> &mut $item {
                &mut self.0[id.0]
            }
        }
    };
}

