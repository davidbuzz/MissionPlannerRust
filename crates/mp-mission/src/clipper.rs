    /// `ClipperBase.Reset`, `clipper.cs:1137-1163`.
    fn reset(&mut self) {
        self.current_lm = self.minima_list;
        if self.current_lm.is_none() {
            return; //ie nothing to process
        }

        //reset all edges ...
        self.scanbeam.clear();
        let mut lm = self.minima_list;
        while let Some(l) = lm {
            let LocalMinima {
                y,
                left_bound,
                right_bound,
                next,
            } = self.minima[l];
            self.insert_scanbeam(y);
            for e in [left_bound, right_bound].into_iter().flatten() {
                self.edges[e].curr = self.edges[e].bot;
                self.edges[e].out_idx = UNASSIGNED;
            }
            lm = next;
        }
        self.active_edges = None;
    }

