/// `PolyTree` and its `PolyNode`s, `clipper.cs:94-203`, as far as the rotary pattern reads them:
/// the outlines at the top level, in order, and the rest of the tree beneath them.
#[derive(Debug, Default)]
pub(crate) struct PolyTree {
    /// `m_AllPolys`: each node's contour and children.
    nodes: Vec<PolyNode>,
    /// `m_Childs` of the tree itself.
    childs: Vec<usize>,
}

#[derive(Debug, Default)]
struct PolyNode {
    polygon: Vec<IntPoint>,
    childs: Vec<usize>,
}

impl PolyTree {
    /// `PolyTree.ChildCount`.
    pub(crate) fn child_count(&self) -> usize {
        self.childs.len()
    }

    /// The `Contour` of each of `PolyTree.Childs`, in order.
    pub(crate) fn child_contours(&self) -> impl Iterator<Item = &[IntPoint]> {
        self.childs
            .iter()
            .filter_map(|&child| self.nodes.get(child))
            .map(|node| node.polygon.as_slice())
    }

    /// `Clipper.ReversePaths(Clipper.PolyTreeToPaths(tree))` (`clipper.cs:3336-3340`,
    /// `:4400-4424`): every non-empty contour reachable from the root, reversed in place -
    /// `PolyTreeToPaths` collects the nodes' own lists, not copies.
    pub(crate) fn reverse_paths(&mut self) {
        let mut stack: Vec<usize> = self.childs.iter().rev().copied().collect();
        while let Some(index) = stack.pop() {
            if let Some(node) = self.nodes.get_mut(index) {
                node.polygon.reverse();
                stack.extend(node.childs.iter().rev().copied());
            }
        }
    }

    /// `PolyTree.Clear`, `clipper.cs:101-107`.
    fn clear(&mut self) {
        self.nodes.clear();
        self.childs.clear();
    }

    /// `PolyNode.AddChild` on the node `parent`, or on the tree itself for `None`.
    fn add_child(&mut self, parent: Option<usize>, child: usize) {
        match parent {
            None => self.childs.push(child),
            Some(parent) => {
                if let Some(node) = self.nodes.get_mut(parent) {
                    node.childs.push(child);
                }
            }
        }
    }
}

/// `Clipper.Round` and `ClipperOffset.Round`, `clipper.cs:3087-3091`, `:4483-4486`: half away
/// from zero, by truncating after adding a half.
fn round(value: f64) -> i64 {
    if value < 0.0 {
        cs_long(value - 0.5)
    } else {
        cs_long(value + 0.5)
    }
}

