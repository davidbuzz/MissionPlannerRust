    /// `Clipper.ExecuteInternal`, `clipper.cs:1533-1583`.
    fn execute_internal(&mut self) -> Result<bool> {
        self.reset();
        self.sorted_edges = None;

        let Some(bot_y) = self.pop_scanbeam() else {
            return Ok(false);
        };
        self.insert_local_minima_into_ael(bot_y)?;
        loop {
            // `PopScanbeam(out topY) || LocalMinimaPending()`: an empty scanbeam gives topY 0.
            let top_y = match self.pop_scanbeam() {
                Some(y) => y,
                None if self.local_minima_pending() => 0,
                None => break,
            };
            self.process_horizontals()?;
            self.ghost_joins.clear();
            if !self.process_intersections(top_y)? {
                return Ok(false);
            }
            self.process_edges_at_top_of_scanbeam(top_y)?;
            self.insert_local_minima_into_ael(top_y)?;
        }

        //fix orientations ...
        for out_rec in self.out_rec_ids() {
            let Some(pts) = self.poly_outs[out_rec].pts else {
                continue;
            };
            if (self.poly_outs[out_rec].is_hole ^ self.reverse_solution)
                == (self.area_op(pts) > 0.0)
            {
                self.reverse_poly_pt_links(pts);
            }
        }

        self.join_common_edges()?;

        for out_rec in self.out_rec_ids() {
            if self.poly_outs[out_rec].pts.is_none() {
                continue;
            }
            self.fixup_out_polygon(out_rec)?;
        }

        // StrictlySimple is false: no DoSimplePolygons (clipper.cs:1574).
        Ok(true)
    }

