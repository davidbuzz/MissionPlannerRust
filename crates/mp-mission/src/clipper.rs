/// `MyIntersectNodeSort.Compare`, `clipper.cs:487-496`: bottom-most (largest Y) first.
fn intersect_node_compare(node1: &IntersectNode, node2: &IntersectNode) -> i32 {
    let i = node2.pt.y.wrapping_sub(node1.pt.y);
    if i > 0 {
        1
    } else if i < 0 {
        -1
    } else {
        0
    }
}

