struct Fixture {
    root: PathBuf,
}

impl Fixture {
    /// A fresh tree, an empty Rust repo beside it, and no ledger yet.
    fn new(name: &str) -> Fixture {
        let root = Path::new(env!("CARGO_TARGET_TMPDIR"))
            .join("ledger")
            .join(name);
        let _ = fs::remove_dir_all(&root);
        let fixture = Fixture { root };
        for (path, _) in EXPECTED {
            let content = if path.to_ascii_lowercase().ends_with(".designer.cs") {
                if path.contains("Resource") || path.contains("HUDT") {
                    STAMPED.to_owned()
                } else {
                    FORM.to_owned()
                }
            } else {
                format!("namespace Fixture.{} {{\n}}\n", stem(path))
            };
            fixture.put(path, &content);
        }
        for (path, lines) in [
            ("Sizes/s199.cs", 199),
            ("Sizes/m200.cs", 200),
            ("Sizes/m599.cs", 599),
            ("Sizes/l600.cs", 600),
            ("Sizes/l1500.cs", 1500),
            ("Sizes/xl1501.cs", 1501),
        ] {
            fixture.put(path, &"//\n".repeat(lines));
        }
        fixture.put(
            "Namespaces/filescoped.cs",
            "using System;\nnamespace Foo.Bar;\n",
        );
        fixture.put("Namespaces/bom.cs", "\u{feff}namespace Bom.First\n{\n}\n");
        fixture.put(
            "Namespaces/commented.cs",
            "/*\nnamespace Not.This\n*/\n// namespace Nor.This\nnamespace Real.One{}\n",
        );
        fixture.put("Namespaces/unterminated.cs", "namespace NoNewline {}");
        fixture.put("Plugins/example.cs", "using System;\nclass Example {}\n");
        // Two project files in one directory: the first by name wins.
        fixture.put("MissionPlannerLib.csproj", "<Project/>");
        fixture.put("MissionPlanner.csproj", "<Project/>");
        fixture.put("ExtLibs/ZedGraph/ZedGraph.csproj", "<Project/>");
        // Not C# sources, whatever they look like.
        fixture.put(".git/objects/ignored.cs", "namespace Git {}\n");
        fixture.put("Upper.CS", "namespace Upper {}\n");
        fixture.put("notes.cs.txt", "namespace Text {}\n");
        fs::create_dir_all(fixture.repo().join("ledger")).unwrap();
        fixture
    }

    fn tree(&self) -> PathBuf {
        self.root.join("tree")
    }

    fn repo(&self) -> PathBuf {
        self.root.join("repo")
    }

    fn ledger(&self) -> PathBuf {
        self.repo().join("ledger/ledger.csv")
    }

    fn put(&self, path: &str, content: &str) {
        put(&self.tree().join(path), content);
    }

    /// Runs `xtask ledger <command>` against this fixture.
    fn run(&self, command: &str) -> Output {
        self.run_with(command, &self.tree())
    }

    fn run_with(&self, command: &str, tree: &Path) -> Output {
        Command::new(env!("CARGO_BIN_EXE_xtask"))
            .args(["ledger", command, "--tree"])
            .arg(tree)
            .arg("--ledger")
            .arg(self.ledger())
            .arg("--repo")
            .arg(self.repo())
            .output()
            .unwrap()
    }

    fn init(&self) -> Output {
        let out = self.run("init");
        assert!(out.status.success(), "init failed: {}", text(&out));
        out
    }

    fn csv(&self) -> String {
        fs::read_to_string(self.ledger()).unwrap()
    }

    /// The row for `path`, by column name. Only rows as `init` wrote them (no quoting) are read
    /// this way; that is the point: the test's reader does not share the tool's.
    fn row(&self, path: &str) -> Vec<(String, String)> {
        let csv = self.csv();
        let mut lines = csv.lines();
        let header: Vec<String> = lines
            .next()
            .unwrap()
            .split(',')
            .map(str::to_owned)
            .collect();
        let line = lines
            .find(|l| l.split(',').next() == Some(path))
            .unwrap_or_else(|| panic!("no row for {path}"));
        header
            .into_iter()
            .zip(line.split(',').map(str::to_owned))
            .collect()
    }

    fn get(&self, path: &str, column: &str) -> String {
        self.row(path)
            .into_iter()
            .find(|(c, _)| c == column)
            .unwrap_or_else(|| panic!("no column {column}"))
            .1
    }

    /// Rewrites columns of one row, quoting as RFC 4180 requires.
    fn edit(&self, path: &str, changes: &[(&str, &str)]) {
        let row = self.row(path);
        let old: Vec<String> = row.iter().map(|(_, v)| quote(v)).collect();
        let new: Vec<String> = row
            .iter()
            .map(|(column, value)| {
                let changed = changes.iter().find(|(c, _)| c == column);
                quote(changed.map_or(value.as_str(), |(_, v)| v))
            })
            .collect();
        let csv = self.csv().replace(
            &format!("{}\n", old.join(",")),
            &format!("{}\n", new.join(",")),
        );
        fs::write(self.ledger(), csv).unwrap();
    }

    /// `check`, which must fail, naming every one of `offenders`.
    fn check_fails(&self, offenders: &[&str]) -> String {
        let out = self.run("check");
        let text = text(&out);
        assert_eq!(out.status.code(), Some(1), "check should fail:\n{text}");
        for offender in offenders {
            assert!(
                text.contains(offender),
                "check did not name `{offender}`:\n{text}"
            );
        }
        text
    }

    fn check_passes(&self) -> String {
        let out = self.run("check");
        let text = text(&out);
        assert!(out.status.success(), "check should pass:\n{text}");
        text
    }
}

fn put(path: &Path, content: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn stem(path: &str) -> String {
    path.rsplit('/')
        .next()
        .unwrap()
        .split('.')
        .next()
        .unwrap()
        .replace('-', "_")
}

fn quote(field: &str) -> String {
    if field.contains([',', '"', '\n']) {
        format!("\"{}\"", field.replace('"', "\"\""))
    } else {
        field.to_owned()
    }
}

fn text(out: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    )
}

#[test]
fn classifier_puts_each_file_in_its_tier() {
    let f = Fixture::new("classifier");
    f.init();
    let rows = f.csv().lines().count() - 1;
    assert_eq!(
        rows,
        EXPECTED.len(),
        "one row per .cs file and nothing else"
    );
    let disposition = |tier: &str| match tier {
        "T0" => "delete",
        "T1" => "regenerate",
        "T2" => "extract",
        "T3" => "hand-port",
        _ => "drop-pending-owner",
    };
    let mut wrong = Vec::new();
    for (path, tier) in EXPECTED {
        let got = f.get(path, "tier");
        if got != *tier {
            wrong.push(format!("{path}: {got}, expected {tier}"));
        }
        assert_eq!(f.get(path, "disposition"), disposition(tier), "{path}");
        assert_eq!(f.get(path, "state"), "ready", "{path}");
    }
    assert!(wrong.is_empty(), "misclassified:\n{}", wrong.join("\n"));
}

#[test]
fn init_measures_every_column_it_owns_and_leaves_the_rest_empty() {
    let f = Fixture::new("measure");
    f.init();

    let bytes = fs::read(f.tree().join("GCSViews/FlightData.cs")).unwrap();
    assert_eq!(
        f.get("GCSViews/FlightData.cs", "sha256"),
        format!("{:x}", Sha256::digest(&bytes))
    );
    assert_eq!(f.get("GCSViews/FlightData.cs", "loc"), "2");

    // The root holds two project files; the first by name is the application.
    assert_eq!(
        f.get("GCSViews/FlightData.cs", "csproj"),
        "MissionPlanner.csproj"
    );
    assert_eq!(
        f.get("ExtLibs/ZedGraph/ZedGraph/ZedGraphControl.cs", "csproj"),
        "ExtLibs/ZedGraph/ZedGraph.csproj"
    );

    for (path, namespace) in [
        ("GCSViews/FlightData.cs", "Fixture.FlightData"),
        ("Namespaces/filescoped.cs", "Foo.Bar"),
        ("Namespaces/bom.cs", "Bom.First"),
        ("Namespaces/commented.cs", "Real.One"),
        ("Namespaces/unterminated.cs", "NoNewline"),
        ("Plugins/example.cs", ""),
    ] {
        assert_eq!(f.get(path, "namespace"), namespace, "{path}");
    }
    // `wc -l`: a last line without a newline is not counted, as in PLAN.md's totals.
    assert_eq!(f.get("Namespaces/unterminated.cs", "loc"), "0");

    for (path, size) in [
        ("Sizes/s199.cs", "S"),
        ("Sizes/m200.cs", "M"),
        ("Sizes/m599.cs", "M"),
        ("Sizes/l600.cs", "L"),
        ("Sizes/l1500.cs", "L"),
        ("Sizes/xl1501.cs", "XL"),
    ] {
        assert_eq!(f.get(path, "size"), size, "{path}");
    }

    for (column, value) in f.row("GCSViews/FlightData.cs") {
        let measured = [
            "path",
            "loc",
            "namespace",
            "csproj",
            "tier",
            "disposition",
            "size",
            "state",
            "sha256",
        ];
        if !measured.contains(&column.as_str()) {
            assert!(
                value.is_empty(),
                "{column} should start empty, is `{value}`"
            );
        }
    }
}

#[test]
fn two_inits_are_byte_identical_and_a_second_run_changes_nothing() {
    let a = Fixture::new("determinism-a");
    let b = Fixture::new("determinism-b");
    a.init();
    b.init();
    let first = a.csv();
    assert_eq!(
        first,
        b.csv(),
        "two trees with the same files, two different ledgers"
    );
    a.init();
    assert_eq!(
        first,
        a.csv(),
        "a refresh over an unchanged tree rewrote the ledger"
    );
    let lines: Vec<&str> = first.lines().skip(1).collect();
    let mut sorted = lines.clone();
    sorted.sort_by_key(|l| l.split(',').next().unwrap().to_owned());
    assert_eq!(lines, sorted, "rows are not in path order");
    assert!(first.ends_with('\n') && !first.contains('\r'));
}

