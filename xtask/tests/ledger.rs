#[test]
fn refresh_keeps_hand_columns_and_flags_upstream_changes() {
    let f = Fixture::new("refresh");
    f.init();
    let notes = "owner said: keep \"as is\", for now\nsecond line";
    f.edit(
        "GCSViews/FlightData.cs",
        &[
            ("state", "ported"),
            ("target_crate", "mp-gui"),
            ("unit_id", "fly-1"),
            ("owner", "agent-7"),
            ("attempts", "2"),
            ("omissions", "none; the HUD"),
            ("notes", notes),
        ],
    );
    f.edit(
        "ExtLibs/Mavlink/MavlinkParse.cs",
        &[("disposition", "regenerate"), ("owner", "buzz")],
    );
    f.edit("ExtLibs/DroneCAN/DroneCAN.cs", &[("state", "ported")]);
    f.edit(
        "GCSViews/FlightData.Designer.cs",
        &[("disposition", "hand-port")],
    );

    // Upstream edits two files: one under work, one nobody has touched. A third appears.
    f.put(
        "GCSViews/FlightData.cs",
        "namespace MissionPlanner.GCSViews {\n// new\n}\n",
    );
    f.put("Plugins/example.cs", "class Changed {}\n");
    f.put(
        "GCSViews/NewScreen.cs",
        "namespace MissionPlanner.GCSViews {}\n",
    );
    // Two forms turn out to be resgen output, so the classifier moves them from T2 to T1.
    f.put("GCSViews/FlightData.Designer.cs", STAMPED);
    f.put("Log/lower.designer.cs", STAMPED);
    let out = f.init();
    assert!(text(&out).contains("1 new, 1 flagged"), "{}", text(&out));

    let csv = f.csv();
    let flight = csv
        .lines()
        .find(|l| l.starts_with("GCSViews/FlightData.cs,"))
        .unwrap();
    // Hand columns survive, including a note that needs quoting across two lines.
    for kept in ["mp-gui", "fly-1", "agent-7", ",2,", ",none; the HUD,"] {
        assert!(flight.contains(kept), "lost {kept}: {flight}");
    }
    assert!(csv.contains(
        "\"owner said: keep \"\"as is\"\", for now\nsecond line; upstream-changed: was ported\""
    ));
    // Measured columns follow the file; work in progress goes back to ready.
    assert!(flight.contains(",3,MissionPlanner.GCSViews,"), "{flight}");
    assert!(flight.contains(",ready,"), "{flight}");

    // Untouched work is not flagged; untouched rows are not annotated.
    assert_eq!(f.get("ExtLibs/DroneCAN/DroneCAN.cs", "state"), "ported");
    assert_eq!(f.get("Plugins/example.cs", "notes"), "");
    assert_eq!(f.get("Plugins/example.cs", "state"), "ready");
    // A chosen disposition is kept, through a reclassification too; a default one follows the
    // tier. A new file arrives ready.
    assert_eq!(
        f.get("ExtLibs/Mavlink/MavlinkParse.cs", "disposition"),
        "regenerate"
    );
    assert_eq!(f.get("GCSViews/FlightData.Designer.cs", "tier"), "T1");
    assert_eq!(
        f.get("GCSViews/FlightData.Designer.cs", "disposition"),
        "hand-port"
    );
    assert_eq!(f.get("Log/lower.designer.cs", "tier"), "T1");
    assert_eq!(f.get("Log/lower.designer.cs", "disposition"), "regenerate");
    assert_eq!(f.get("GCSViews/NewScreen.cs", "state"), "ready");

    // And the whole file is still what a refresh of itself produces.
    let once = f.csv();
    f.init();
    assert_eq!(once, f.csv());
}

