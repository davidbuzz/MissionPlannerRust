//! `cargo xtask ledger`, driven as a person or CI would drive it: through the binary, over a
//! small C# tree each test writes for itself.
//!
//! The fixture holds one file for every rule the classifier has and for each way a rule could
//! over-match (a file named like a vendored one, a form whose name ends in `Settings.Designer.cs`),
//! so a wrong precedence or a prefix without its slash fails here rather than silently moving a
//! few hundred rows of the real ledger into the wrong tier.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::indexing_slicing)]

