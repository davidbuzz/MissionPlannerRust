#[test]
fn status_reports_retired_lines_in_the_plan_shape() {
    let f = Fixture::new("status");
    f.init();
    done_row(&f);
    f.edit("Sizes/l600.cs", &[("state", "dropped"), ("notes", "dead")]);
    f.edit(
        "ExtLibs/ZedGraph/ZedGraph/ZedGraphControl.cs",
        &[("state", "dropped"), ("notes", "mp-chart")],
    );
    f.edit("Sizes/xl1501.cs", &[("state", "reviewed")]);
    let out = f.run("status");
    assert!(out.status.success(), "{}", text(&out));
    let stdout = String::from_utf8_lossy(&out.stdout);
    // T0: ZedGraphControl.cs (2). T3: FlightData.cs (2) done + l600.cs (600) dropped, of every
    // T3 line in the fixture; `reviewed` is not retired.
    let t3_total: usize = EXPECTED
        .iter()
        .filter(|(_, tier)| *tier == "T3")
        .map(|(path, _)| f.get(path, "loc").parse::<usize>().unwrap())
        .sum();
    let t3_total = if t3_total >= 1000 {
        format!("{},{:03}", t3_total / 1000, t3_total % 1000)
    } else {
        t3_total.to_string()
    };
    assert_eq!(
        stdout.lines().next().unwrap(),
        format!("T0 2 retired / T1 0 generated / T2 0 extracted / T3 602 done of {t3_total}")
    );
    assert!(stdout.contains("states: ready "), "{stdout}");
    assert!(stdout.contains(" reviewed 1 done 1 dropped 2"), "{stdout}");
}

