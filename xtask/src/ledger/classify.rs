fn matches(roots: &[&str], path: &str) -> bool {
    roots.iter().any(|root| {
        if root.ends_with('/') {
            path.starts_with(root)
        } else {
            path == *root
        }
    })
}

fn is_designer(path: &str) -> bool {
    // Both spellings occur in the tree (`Resource.designer.cs` is the Android generator's).
    path.to_ascii_lowercase().ends_with(".designer.cs")
}

/// Classifies one file. `path` is relative to the C# root with `/` separators; `content` is the
/// file's bytes (only the head of a designer file is looked at).
pub fn classify(path: &str, content: &[u8]) -> Tier {
    if matches(VENDORED, path) {
        return Tier::T0;
    }
    if matches(GENERATED, path) || (is_designer(path) && has_generator_stamp(content)) {
        return Tier::T1;
    }
    if matches(NON_DESKTOP, path) {
        return Tier::T4;
    }
    if is_designer(path) {
        return Tier::T2;
    }
    Tier::T3
}

fn has_generator_stamp(content: &[u8]) -> bool {
    let head = content.get(..STAMP_WINDOW).unwrap_or(content);
    head.windows(b"<auto-generated".len())
        .any(|w| w == b"<auto-generated")
}
