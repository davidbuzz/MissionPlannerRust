//! The tier classifier (PLAN.md §4): a pure function of a file's path and its first bytes.
//!
//! Rules are tried in order and the first match wins:
//!
//! 1. **T0 vendored** — under a root in [`VENDORED`]. Every root carries its evidence: listed in
//!    PLAN.md §4.1, or a licence/copyright header, a LICENSE/COPYING/README, or package metadata
//!    naming someone other than Mission Planner. A generated or designer file inside a vendored
//!    library goes with the library: nothing is regenerated or extracted from code that is
//!    deleted.
//! 2. **T1 generated** — a file a generator in the tree emits ([`GENERATED`]), or a
//!    `*.designer.cs` carrying the `<auto-generated>` stamp that resgen, the settings designer
//!    and the Android resource generator all write and the WinForms designer never does. The
//!    stamp, not the file name, decides: `Controls/DefaultSettings.Designer.cs` is a form that
//!    happens to end in `Settings.Designer.cs`.
//! 3. **T4 non-desktop** — the application heads for platforms PLAN.md §1.2 does not target
//!    ([`NON_DESKTOP`]); their fate is the owner's ruling, not a porter's.
//! 4. **T2 designer** — every other `*.designer.cs`: WinForms layout for a form or control.
//! 5. **T3 hand-port** — everything else.

/// Bytes of a designer file searched for the generator's stamp; it is always in the header.
const STAMP_WINDOW: usize = 2048;

/// A tier from PLAN.md §4.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Tier {
    /// Vendored third-party code: deleted, replaced by crates.
    T0,
    /// Machine-generated code: regenerated from the definitions in the tree.
    T1,
    /// WinForms designer output: extracted to a screen spec.
    T2,
    /// Mission Planner's own code: hand-ported.
    T3,
    /// Code for platforms the port does not target: dropped pending the owner's ruling.
    T4,
}

impl Tier {
    /// Every tier, in report order.
    pub const ALL: [Tier; 5] = [Tier::T0, Tier::T1, Tier::T2, Tier::T3, Tier::T4];

    /// The ledger spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            Tier::T0 => "T0",
            Tier::T1 => "T1",
            Tier::T2 => "T2",
            Tier::T3 => "T3",
            Tier::T4 => "T4",
        }
    }

    /// Parses the ledger spelling.
    pub fn parse(s: &str) -> Option<Tier> {
        Tier::ALL.into_iter().find(|t| t.as_str() == s)
    }

    /// What PLAN.md §4 does with a file of this tier. A row may override it (§4.1 allows
    /// hand-porting `MGRS.cs` out of vendored GeoUtility), so this is only the starting value.
    pub fn disposition(self) -> &'static str {
        match self {
            Tier::T0 => "delete",
            Tier::T1 => "regenerate",
            Tier::T2 => "extract",
            Tier::T3 => "hand-port",
            Tier::T4 => "drop-pending-owner",
        }
    }
}

